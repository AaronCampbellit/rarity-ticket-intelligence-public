func NewContractCreateTool(directory ActiveClientResolver, creator ContractCreator, newID func() string) aiassist.Tool {
	return &functionalTool{
		name: "contract.create", capability: "contract.create", kind: aiassist.ToolWrite,
		prepare: func(ctx context.Context, principal authorization.Principal, raw json.RawMessage) (json.RawMessage, error) {
			request, err := decode[contractCreateRequest](raw)
			if err != nil || creator == nil || !optionalValueValid(request.EndsOn) || !validDate(request.StartsOn) || (request.EndsOn != nil && !validDate(*request.EndsOn)) {
				return nil, aiassist.ErrInvalidTool
			}
			if request.EndsOn != nil && !dateNotBefore(*request.EndsOn, request.StartsOn) {
				return nil, aiassist.ErrInvalidTool
			}
			input, err := prepareResourceCreate(ctx, directory, principal, "contract.create", request.Client, request.DisplayID, request.Name, newID)
			if err != nil {
				return nil, err
			}
			input.StartsOn, input.EndsOn = strings.TrimSpace(request.StartsOn), optionalValue(request.EndsOn)
			return marshalPrepared(input)
		},
		validate: validateContractCreate,
		resolve:  resolveClientResourceScope,
		preview: func(ctx context.Context, principal authorization.Principal, raw json.RawMessage) (aiassist.Preview, error) {
			input, err := validContractCreate(raw)
			if err != nil {
				return aiassist.Preview{}, err
			}
			changes := baseResourceChanges(input)
			changes["starts_on"] = aiassist.Change{Before: nil, After: input.StartsOn}
			if input.EndsOn != "" {
				changes["ends_on"] = aiassist.Change{Before: nil, After: input.EndsOn}
			}
			return createResourcePreview(ctx, directory, principal, "contract.create", "contract", input, changes)
		},
		execute: func(ctx context.Context, principal authorization.Principal, raw json.RawMessage, correlationID string) (aiassist.ToolResult, error) {
			input, err := validContractCreate(raw)
			if err != nil || creator == nil {
				return aiassist.ToolResult{}, aiassist.ErrInvalidTool
			}
			startsOn, _ := parseDate(input.StartsOn)
			var endsOn *time.Time
			if input.EndsOn != "" {
				value, _ := parseDate(input.EndsOn)
				endsOn = &value
			}
			created, err := creator.CreateContract(ctx, clientresources.CreateContractCommand{
				Principal: principal, Target: target(principal, input.ClientID), DisplayID: input.DisplayID, Name: input.Name, StartsOn: startsOn, EndsOn: endsOn,
				ActorID: principal.ID, Source: "ai_workspace", Prepared: preparedIdentity(input, correlationID),
			})
			if err != nil {
				return aiassist.ToolResult{}, err
			}
			return resourceResult("contract", created.ID, created.DisplayID, created.Name), nil
		},
	}
}

func resolveActiveResourceClient(ctx context.Context, directory ActiveClientResolver, principal authorization.Principal, capability, reference string) (organizations.Client, error) {
	if directory == nil || strings.TrimSpace(principal.Scope.MSPID) == "" {
		return organizations.Client{}, aiassist.ErrInvalidTool
	}
	return directory.ResolveActiveClient(ctx, principal, capability, strings.TrimSpace(reference))
}

func prepareResourceCreate(ctx context.Context, directory ActiveClientResolver, principal authorization.Principal, capability, clientReference, displayID, name string, newID func() string) (resourceCreatePrepared, error) {
	if newID == nil || strings.TrimSpace(displayID) == "" || strings.TrimSpace(name) == "" {
		return resourceCreatePrepared{}, aiassist.ErrInvalidTool
	}
	client, err := resolveActiveResourceClient(ctx, directory, principal, capability, clientReference)
	if err != nil {
		return resourceCreatePrepared{}, err
	}
	resourceID := strings.TrimSpace(newID())
	if resourceID == "" {
		return resourceCreatePrepared{}, aiassist.ErrInvalidTool
	}
	return resourceCreatePrepared{ClientID: client.ID, ClientReference: strings.TrimSpace(clientReference), ClientName: client.Name, ClientDisplayID: client.DisplayID, ResourceID: resourceID, DisplayID: strings.TrimSpace(displayID), Name: strings.TrimSpace(name)}, nil
}

func prepareLocationReference(ctx context.Context, catalog ClientResourceCatalog, principal authorization.Principal, capability, clientID string, reference *string) (string, error) {
	if reference == nil {
		return "", nil
	}
	if catalog == nil || strings.TrimSpace(*reference) == "" {
		return "", aiassist.ErrInvalidTool
	}
	location, err := catalog.ResolveTrusted(ctx, clientresources.TrustedResolveCommand{
		Principal: principal, Target: target(principal, clientID), Kind: clientresources.LocationKind,
		Reference: strings.TrimSpace(*reference), Capability: capability,
	})
	if err != nil {
		return "", err
	}
	if !isActiveLocation(location) {
		return "", clientresources.ErrLifecycleConflict
	}
	return location.ID, nil
}

func currentActiveLocation(ctx context.Context, catalog ClientResourceCatalog, principal authorization.Principal, capability, clientID, locationID string) (clientresources.ResourceDetail, error) {
	if catalog == nil {
		return clientresources.ResourceDetail{}, aiassist.ErrInvalidTool
	}
	location, err := catalog.GetTrusted(ctx, clientresources.TrustedGetCommand{
		Principal: principal, Target: target(principal, clientID), Kind: clientresources.LocationKind,
		ID: locationID, Capability: capability,
	})
	if err != nil {
		return clientresources.ResourceDetail{}, err
	}
	if !isActiveLocation(location) {
		return clientresources.ResourceDetail{}, clientresources.ErrLifecycleConflict
	}
	return location, nil
}

func isActiveLocation(location clientresources.ResourceDetail) bool {
	return strings.TrimSpace(location.ID) != "" && location.Kind == string(clientresources.LocationKind) && location.LifecycleState == "active"
}

func resolveClientResourceScope(principal authorization.Principal, raw json.RawMessage) (scope.Target, error) {
	return resolveScoped(principal, raw)
}

func marshalPrepared(value any) (json.RawMessage, error) {
	prepared, err := json.Marshal(value)
	if err != nil {
		return nil, aiassist.ErrInvalidTool
	}
	return prepared, nil
}

