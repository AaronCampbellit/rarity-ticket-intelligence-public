func NewClientResourceListTool(
	directory ActiveClientResolver,
	catalog ClientResourceCatalog,
) aiassist.Tool {
	return &functionalTool{
		name: "client_resource.list", capability: "search.read", kind: aiassist.ToolRead,
		prepare: func(ctx context.Context, principal authorization.Principal, raw json.RawMessage) (json.RawMessage, error) {
			request, err := decode[clientResourceListRequest](raw)
			if err != nil || directory == nil || catalog == nil || strings.TrimSpace(request.Client) == "" || !validResourceKind(request.Kind) {
				return nil, aiassist.ErrInvalidTool
			}
			limit := 25
			if request.Limit != nil {
				limit = *request.Limit
			}
			if limit < 1 || limit > 50 || !optionalValueValid(request.Query) {
				return nil, aiassist.ErrInvalidTool
			}
			client, err := resolveActiveResourceClient(ctx, directory, principal, "search.read", request.Client)
			if err != nil {
				return nil, err
			}
			return marshalPrepared(clientResourceListInput{ClientID: client.ID, Kind: request.Kind, Query: optionalValue(request.Query), Limit: limit})
		},
		validate: func(raw json.RawMessage) error {
			input, err := decode[clientResourceListInput](raw)
			if err != nil || strings.TrimSpace(input.ClientID) == "" || !validResourceKind(input.Kind) || input.Limit < 1 || input.Limit > 50 {
				return aiassist.ErrInvalidTool
			}
			return nil
		},
		resolve: resolveClientResourceScope,
		preview: noPreview,
		execute: func(ctx context.Context, principal authorization.Principal, raw json.RawMessage, _ string) (aiassist.ToolResult, error) {
			input, err := decode[clientResourceListInput](raw)
			if err != nil || catalog == nil {
				return aiassist.ToolResult{}, aiassist.ErrInvalidTool
			}
			items, err := catalog.Query(ctx, clientresources.QueryCommand{
				Principal: principal, Target: target(principal, input.ClientID),
				Query: clientresources.Query{Kind: input.Kind, Literal: input.Query, Limit: input.Limit},
			})
			if err != nil {
				return aiassist.ToolResult{}, err
			}
			resources := make([]clientresources.Summary, 0, len(items))
			for _, item := range items {
				if item.LifecycleState != "active" {
					return aiassist.ToolResult{}, aiassist.ErrInvalidTool
				}
				resources = append(resources, item.Summary)
			}
			return aiassist.ToolResult{Summary: "Listed client resources", Data: map[string]any{"resources": resources}}, nil
		},
	}
}

