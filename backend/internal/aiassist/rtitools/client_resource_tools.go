func resourceLocationRef(principal authorization.Principal, clientID, locationID string) clientresources.Ref {
	if locationID == "" {
		return clientresources.Ref{}
	}
	return clientresources.Ref{ID: locationID, MSPID: principal.Scope.MSPID, ClientID: clientID}
}

func resourceResult(kind, id, displayID, name string) aiassist.ToolResult {
	return aiassist.ToolResult{Summary: "Created " + displayID, Data: map[string]any{"resource_type": kind, "resource_id": id, "display_id": displayID, "name": name}}
}

func optionalValue(value *string) string {
	if value == nil {
		return ""
	}
	return strings.TrimSpace(*value)
}
func optionalValueValid(value *string) bool { return value == nil || strings.TrimSpace(*value) != "" }
func validDate(value string) bool {
	_, err := parseDate(value)
	return strings.TrimSpace(value) != "" && err == nil
}
func parseDate(value string) (time.Time, error) {
	return time.Parse("2006-01-02", strings.TrimSpace(value))
}
func dateNotBefore(end, start string) bool {
	endDate, endErr := parseDate(end)
	startDate, startErr := parseDate(start)
	return endErr == nil && startErr == nil && !endDate.Before(startDate)
}

func validResourceKind(kind clientresources.Kind) bool {
	switch kind {
	case clientresources.LocationKind, clientresources.ContactKind, clientresources.AssetKind, clientresources.ServiceKind, clientresources.ContractKind:
		return true
	default:
		return false
	}
}

func validCriticality(value string) bool {
	switch strings.TrimSpace(value) {
	case "low", "normal", "high", "critical":
		return true
	default:
		return false
	}
}
