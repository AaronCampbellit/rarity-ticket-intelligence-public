func NewContactCreateTool(directory ActiveClientResolver, catalog ClientResourceCatalog, creator ContactCreator, newID func() string) aiassist.Tool {
	return &functionalTool{
		name: "contact.create", capability: "contact.create", kind: aiassist.ToolWrite,
		prepare: func(ctx context.Context, principal authorization.Principal, raw json.RawMessage) (json.RawMessage, error) {
			request, err := decode[contactCreateRequest](raw)
			if err != nil || creator == nil || !optionalValueValid(request.Email) || !optionalValueValid(request.Phone) || !optionalValueValid(request.Location) {
				return nil, aiassist.ErrInvalidTool
			}
			input, err := prepareResourceCreate(ctx, directory, principal, "contact.create", request.Client, request.DisplayID, request.DisplayName, newID)
			if err != nil {
				return nil, err
			}
			input.Email = optionalValue(request.Email)
			input.Phone = optionalValue(request.Phone)
			if input.LocationID, err = prepareLocationReference(ctx, catalog, principal, "contact.create", input.ClientID, request.Location); err != nil {
				return nil, err
			}
			return marshalPrepared(input)
		},
		validate: validateContactCreate,
		resolve:  resolveClientResourceScope,
		preview: func(ctx context.Context, principal authorization.Principal, raw json.RawMessage) (aiassist.Preview, error) {
			input, err := validContactCreate(raw)
			if err != nil {
				return aiassist.Preview{}, err
			}
			changes := baseResourceChanges(input)
			var locationTarget *aiassist.PreviewTarget
			changes["display_name"] = aiassist.Change{Before: nil, After: input.Name}
			delete(changes, "name")
			if input.Email != "" {
				changes["email"] = aiassist.Change{Before: nil, After: input.Email}
			}
			if input.Phone != "" {
				changes["phone"] = aiassist.Change{Before: nil, After: input.Phone}
			}
			if input.LocationID != "" {
				location, err := currentActiveLocation(ctx, catalog, principal, "contact.create", input.ClientID, input.LocationID)
				if err != nil {
					return aiassist.Preview{}, err
				}
				changes["location"] = aiassist.Change{Before: nil, After: location.DisplayID}
				locationTarget = previewLocationTarget(input.ClientID, location)
			}
			preview, err := createResourcePreview(ctx, directory, principal, "contact.create", "contact", input, changes)
			if err != nil {
				return aiassist.Preview{}, err
			}
			preview.LocationTarget = locationTarget
			return preview, nil
		},
		execute: func(ctx context.Context, principal authorization.Principal, raw json.RawMessage, correlationID string) (aiassist.ToolResult, error) {
			input, err := validContactCreate(raw)
			if err != nil || creator == nil {
				return aiassist.ToolResult{}, aiassist.ErrInvalidTool
			}
			created, err := creator.CreateContact(ctx, clientresources.CreateContactCommand{
				Principal: principal, Target: target(principal, input.ClientID), Location: resourceLocationRef(principal, input.ClientID, input.LocationID),
				DisplayID: input.DisplayID, DisplayName: input.Name, Email: input.Email, Phone: input.Phone, ActorID: principal.ID, Source: "ai_workspace", Prepared: preparedIdentity(input, correlationID),
			})
			if err != nil {
				return aiassist.ToolResult{}, err
			}
			return resourceResult("contact", created.ID, created.DisplayID, created.DisplayName), nil
		},
	}
}

